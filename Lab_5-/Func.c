void PointerTest(int* x) {

    // Виводимо адресу (посилання) за допомогою %p
    printf("Посилання на область в пам'яті: %p\n", x);

    // Виводимо значення за допомогою *x та %d
    printf("Значення в цій області пам'яті: %d\n", *x);

    // Множимо значення за посиланням на 2
    *x *= 2; 

    // Виводимо результат після множення
    printf("Значення в цій області пам'яті після множення: %d\n", *x);



}